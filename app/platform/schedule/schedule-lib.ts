/**
 * Shared calendar vocabulary — the DTO the server hands the schedule page,
 * the date helpers every renderer uses, and the lifecycle tones. Pulled out
 * of ScheduleClient so the month grid, time grid, palette, and sheets can be
 * separate files that agree on one set of types.
 */

// Blocked-off time riding along in the DTO — the calendar shows per-day
// segments but the sheet edits the underlying block's full range.
export type BlockInfo = {
  id: string;
  userId: string | null; // null = everyone (company-wide)
  userName: string | null;
  title: string;
  startAt: string;
  endAt: string;
  allDay: boolean;
  /** Optional "where I'll be" — routing treats a located block as a stop. */
  address: string | null;
  canEdit: boolean;
  /** GOOGLE = mirrored from the user's Google Calendar; read-only here. */
  source: "MANUAL" | "GOOGLE";
};

export type ScheduleJobDTO = {
  id: string;
  kind: "job" | "appointment" | "block";
  jobNumber: number | null;
  title: string;
  status: string;
  apptType: string | null; // PHONE_CALL | VIDEO_CALL | IN_PERSON
  scheduledAt: string | null;
  scheduledEnd: string | null;
  scheduledAnytime: boolean;
  contactName: string;
  contactId?: string | null;
  tentative?: boolean; // self-scheduled booking awaiting approval → dashed
  requestId?: string | null; // tentative bookings accept through their request
  recurring?: boolean; // visit generated by a subscription's visit series
  // Auto-generated visit landed on existing work (Job.conflictNote) — badge
  // until someone reschedules it
  conflictNote?: string | null;
  assignees?: string[]; // who's on it — initials chips on the phone agenda
  assigneeIds?: string[]; // prefills the drop-to-schedule sheet's crew picker
  outsourced?: boolean; // a subcontractor is doing it — empty crew on purpose
  // Scheduled, nobody on it, not outsourced, and the company has more than
  // one member (a one-person company's jobs are auto-assigned) → badge it
  needsCrew?: boolean;
  // Phone agenda swipe actions (call / directions); absent on blocks
  phone?: string | null;
  address?: string | null;
  block?: BlockInfo;
};

